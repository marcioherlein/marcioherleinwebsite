import { test,expect } from '@playwright/test'

test('project destinations, authentic assets, and the identity stage',async({page})=>{
 await page.goto('/')
 await expect(page.locator('.project a[href*="github.com"]')).toHaveCount(0)
 await expect(page.getByRole('link',{name:'Visit globalshipping.app'})).toHaveAttribute('href','https://globalshipping.app')
 await expect(page.getByRole('link',{name:'Visit insic.app'})).toHaveAttribute('href','https://insic.app')
 await expect(page.getByRole('heading',{name:/Research agents\.\s*Publishing bots\./})).toBeVisible()
 await expect(page.getByRole('heading',{name:'A research agent with web search.'})).toBeVisible()
 const identity=page.locator('#identity-output')
 await expect(identity.locator('strong')).toHaveText('Complete scooter')
 await page.getByLabel('Choose a product description').selectOption('battery')
 await expect(identity.locator('strong')).toHaveText('Battery')
 await expect(identity.locator('dd')).toHaveText('lithium battery')
 await page.getByLabel('Choose a product description').selectOption('charger')
 await expect(identity.locator('strong')).toHaveText('Charger / power adapter')
 await expect(identity).toContainText('No tariff code or duty rate is assigned')
 for(const image of ['/projects/insic-logo.svg','/projects/globalshipping-mark.svg','/projects/erm-brief-edited.png','/projects/globalshipping-mobile-intake.jpg']){
  const response=await page.request.get(image)
  expect(response.status()).toBe(200)
  expect(response.headers()['content-type']).toMatch(/image\//)
 }
})

test('galleries filter devices, browse with keys, and enlarge accessibly',async({page})=>{
 await page.goto('/')
 const gallery=page.getByRole('region',{name:'Insic product gallery',exact:true})
 await expect(gallery.locator('.gallery-counter')).toHaveText('1 / 4')
 await gallery.getByRole('button',{name:'Next Insic image',exact:true}).click()
 await expect(gallery.locator('.gallery-counter')).toHaveText('2 / 4')
 const stage=gallery.locator('.gallery-stage')
 await stage.focus();await page.keyboard.press('ArrowRight')
 await expect(gallery.locator('.gallery-counter')).toHaveText('3 / 4')
 await page.keyboard.press('Home')
 await expect(gallery.locator('.gallery-counter')).toHaveText('1 / 4')
 await gallery.getByRole('button',{name:'Mobile',exact:true}).click()
 await expect(gallery.locator('.gallery-counter')).toHaveText('1 / 1')
 await expect(gallery.locator('.gallery-image')).toHaveAttribute('src','/projects/insic-mobile.png')
 await expect(gallery.getByRole('button',{name:'Next Insic image',exact:true})).toBeDisabled()
 await gallery.getByRole('button',{name:'Enlarge Insic image',exact:true}).click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await expect(page.getByRole('dialog')).toContainText('Saved mobile stock-page capture')
 await page.keyboard.press('Escape')
 await expect(page.getByRole('dialog')).not.toBeVisible()
 await expect(gallery.getByRole('button',{name:'Enlarge Insic image',exact:true})).toBeFocused()
 await gallery.getByRole('button',{name:'Desktop',exact:true}).click()
 await expect(gallery.locator('.gallery-counter')).toHaveText('1 / 3')
 await gallery.getByRole('button',{name:/Show A second company/}).click()
 await expect(gallery.locator('.gallery-image')).toHaveAttribute('src','/projects/insic-nvda.png')
 const shipping=page.getByRole('region',{name:'GlobalShipping product gallery',exact:true})
 await shipping.getByRole('button',{name:'Mobile',exact:true}).click()
 await expect(shipping.locator('.gallery-counter')).toHaveText('1 / 2')
 await shipping.getByRole('button',{name:'Next GlobalShipping image',exact:true}).click()
 await expect(shipping.locator('.gallery-image')).toHaveAttribute('src','/projects/globalshipping-mobile-intake.jpg')
 const erm=page.getByRole('region',{name:'ERM Intelligence product gallery',exact:true})
 await expect(erm).toContainText('AI-edited visual')
 await erm.getByRole('button',{name:'Next ERM Intelligence image',exact:true}).click()
 await expect(erm.locator('.gallery-caption')).toContainText('Risk Quantifier')
})

test('a failed gallery image is recoverable and never becomes a working enlarge button',async({page})=>{
 await page.route('**/projects/insic-valuation.png',route=>route.abort())
 await page.goto('/')
 const gallery=page.getByRole('region',{name:'Insic product gallery',exact:true})
 await gallery.getByRole('button',{name:'Next Insic image',exact:true}).click()
 await expect(gallery.getByRole('alert')).toBeVisible()
 await expect(gallery.getByRole('button',{name:'Enlarge Insic image',exact:true})).toBeDisabled()
 await gallery.getByRole('button',{name:'Next Insic image',exact:true}).click()
 await expect(gallery.getByRole('alert')).toBeHidden()
 await expect(gallery.getByRole('button',{name:'Enlarge Insic image',exact:true})).toBeEnabled()
})
