import { test, expect } from '@playwright/test'

test('case studies link to the products and use actual image assets', async ({ page }) => {
  await page.goto('/work/insic/')
  await expect(page.locator('a[href="https://insic.app"]').first()).toBeVisible()
  await expect(page.getByRole('main')).toContainText(/agent/i)
  await expect(page.getByRole('main')).toContainText(/LinkedIn/i)
  await page.goto('/work/globalshipping/')
  await expect(page.locator('a[href="https://globalshipping.app"]').first()).toBeVisible()
  await expect(page.getByRole('main')).toContainText(/classif/i)
  for (const image of ['/projects/insic-logo.svg', '/projects/globalshipping-mark.svg', '/projects/erm-brief-edited.png', '/projects/globalshipping-mobile-intake.jpg']) {
    const response = await page.request.get(image)
    expect(response.status(), image).toBe(200)
    expect(response.headers()['content-type'], image).toMatch(/image\//)
  }
})

test('galleries browse by keyboard, filter screen formats, and reserve image space', async ({ page, isMobile }) => {
  await page.goto('/work/insic/')
  const gallery = page.getByRole('region', { name: 'Insic product gallery', exact: true })
  await expect(gallery.locator('.gallery-counter')).toHaveText(isMobile ? '1 / 1' : '1 / 4')
  if (isMobile) await expect(gallery.locator('.gallery-image')).toHaveAttribute('src', '/projects/insic-mobile.png')

  await gallery.getByRole('button', { name: 'All views', exact: true }).click()
  const stage = gallery.locator('.gallery-stage')
  await stage.focus()
  await page.keyboard.press('Home')
  await expect(gallery.locator('.gallery-counter')).toHaveText('1 / 4')
  await page.keyboard.press('ArrowRight')
  await expect(gallery.locator('.gallery-counter')).toHaveText('2 / 4')
  await page.keyboard.press('End')
  await expect(gallery.locator('.gallery-counter')).toHaveText('4 / 4')
  await page.keyboard.press('ArrowLeft')
  await expect(gallery.locator('.gallery-counter')).toHaveText('3 / 4')

  const desktopSize = await stage.boundingBox()
  await gallery.getByRole('button', { name: 'Mobile', exact: true }).click()
  await expect(gallery.locator('.gallery-counter')).toHaveText('1 / 1')
  await expect(gallery.locator('.gallery-image')).toHaveAttribute('src', '/projects/insic-mobile.png')
  await expect(gallery.getByRole('button', { name: 'Next Insic image', exact: true })).toBeDisabled()
  const mobileSize = await stage.boundingBox()
  expect(Math.abs(mobileSize!.height - desktopSize!.height)).toBeLessThan(1)
  const image = gallery.locator('.gallery-image')
  expect(Number(await image.getAttribute('width'))).toBeGreaterThan(0)
  expect(Number(await image.getAttribute('height'))).toBeGreaterThan(0)
  await gallery.locator('.capture-provenance summary').click()
  await expect(gallery.locator('.capture-origin')).toContainText(/not live|not current/i)

  await gallery.getByRole('button', { name: 'Desktop', exact: true }).click()
  await expect(gallery.locator('.gallery-counter')).toHaveText('1 / 3')
  await gallery.getByRole('button', { name: /Show A second company/ }).click()
  await expect(gallery.locator('.gallery-image')).toHaveAttribute('src', '/projects/insic-nvda.png')

  await page.goto('/work/globalshipping/')
  const shipping = page.getByRole('region', { name: 'GlobalShipping product gallery', exact: true })
  await shipping.getByRole('button', { name: 'Mobile', exact: true }).click()
  await expect(shipping.locator('.gallery-counter')).toHaveText('1 / 2')
  await shipping.getByRole('button', { name: 'Next GlobalShipping image', exact: true }).click()
  await expect(shipping.locator('.gallery-image')).toHaveAttribute('src', '/projects/globalshipping-mobile-intake.jpg')

  await page.goto('/work/enterprise-risk/')
  await page.locator('.reference-details > summary').click()
  const erm = page.getByRole('region', { name: 'ERM Intelligence product gallery', exact: true })
  await expect(erm).toContainText('AI-edited interface visual')
  await erm.getByRole('button', { name: 'Next ERM Intelligence image', exact: true }).click()
  await expect(erm.locator('.gallery-caption')).toContainText('Risk Quantifier')
})

test('enlarged captures support readable zoom, original files, and Escape focus return', async ({ page }) => {
  await page.goto('/work/insic/')
  const gallery = page.getByRole('region', { name: 'Insic product gallery', exact: true })
  await gallery.getByRole('button', { name: 'Desktop', exact: true }).click()
  const enlarge = gallery.getByRole('button', { name: 'Enlarge Insic image', exact: true })
  await enlarge.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('link', { name: 'Open original image', exact: true })).toHaveAttribute('href', '/projects/insic-research.png')
  await dialog.getByRole('button', { name: '100%', exact: true }).click()
  await expect(dialog.locator('.dialog-image')).toHaveAttribute('data-zoom', 'actual')
  expect(await dialog.locator('.dialog-image img').evaluate(image => image.getBoundingClientRect().width)).toBe(1280)
  await dialog.getByRole('button', { name: '200%', exact: true }).click()
  expect(await dialog.locator('.dialog-image img').evaluate(image => image.getBoundingClientRect().width)).toBe(2560)
  await dialog.getByRole('button', { name: 'Fit', exact: true }).click()
  await expect(dialog.locator('.dialog-image')).toHaveAttribute('data-zoom', 'fit')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(enlarge).toBeFocused()
})

test('a failed gallery image is recoverable and cannot be enlarged', async ({ page }) => {
  await page.route('**/projects/insic-valuation.png', route => route.abort())
  await page.goto('/work/insic/')
  const gallery = page.getByRole('region', { name: 'Insic product gallery', exact: true })
  await gallery.getByRole('button', { name: 'Desktop', exact: true }).click()
  await gallery.getByRole('button', { name: 'Next Insic image', exact: true }).click()
  await expect(gallery.getByRole('alert')).toBeVisible()
  await expect(gallery.getByRole('button', { name: 'Enlarge Insic image', exact: true })).toBeDisabled()
  await gallery.getByRole('button', { name: 'Next Insic image', exact: true }).click()
  await expect(gallery.getByRole('alert')).toBeHidden()
  await expect(gallery.getByRole('button', { name: 'Enlarge Insic image', exact: true })).toBeEnabled()
})
